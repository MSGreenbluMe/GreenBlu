export function getQuestionById(questionId: string): PersonalityQuestion | undefined {
  return PERSONALITY_QUESTIONS.find(q => q.question_id === questionId);
}

export function getQuestionsByFramework(framework: string): PersonalityQuestion[] {
  return PERSONALITY_QUESTIONS.filter(q => q.framework === framework);
}

export function getQuestionsByDimension(framework: string, dimension: string): PersonalityQuestion[] {
  return PERSONALITY_QUESTIONS.filter(
    q => q.framework === framework && q.dimension === dimension
  );
}

